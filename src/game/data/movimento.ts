/**
 * Limites do fator. O Furness não converge para aeroporto quase isolado — um
 * doméstico num país de dois aeroportos tem um punhado de pares para carregar o
 * movimento inteiro, e o ajuste empurra o fator dele para a casa das centenas.
 * O teto corta esse exagero; o que sobra é contido pelo teto por par do
 * `demand.ts`, que impede qualquer ligação de passar de metade do movimento da
 * ponta menor. Nos aeroportos que importam o fator nem encosta nos limites:
 * Guarulhos 1,60, Congonhas 1,91, Viracopos 0,38, Heathrow 0,41.
 */
const FLUXO_MIN = 0.02
const FLUXO_MAX = 6

