/**
 * Estimativa para quem não está na tabela: bacia, poder de compra, degrau e
 * pista.
 *
 * Os coeficientes saem de uma regressão em log sobre os 2.101 aeroportos com
 * dado — não são chute, são o melhor ajuste possível com o que o catálogo
 * guarda. E o ajuste continua ruim: o erro típico é um fator de **2,51**,
 * porque nada do que o catálogo sabe explica movimento de aeroporto. A pista
 * entrou porque é o que mais ajuda depois do degrau, e ainda assim não resolve.
 * Serve de piso para aeroporto regional, que é onde ele é usado; onde havia
 * dado, o dado manda.
 */
export function estimarMovimento(
  pop: number, gdp: number, tier: number, runway: number,
): number {
  return Math.exp(
    -1.3605 +
      0.3478 * Math.log(Math.max(0.02, pop)) +
      0.6666 * Math.log(gdp) +
      0.7367 * tier +
      1.5681 * Math.log(Math.max(1000, runway)),
  )
}

