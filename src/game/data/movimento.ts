/**
 * Estimativa para quem não está na tabela, da bacia e do degrau.
 *
 * Os coeficientes saem de uma regressão em log sobre os 1.104 aeroportos com
 * dado — não são chute, são o melhor ajuste possível com o que o catálogo
 * guarda. E o ajuste é ruim: o erro típico é um fator de **2,52**, porque
 * população e degrau simplesmente não explicam movimento de aeroporto. Serve de
 * piso para aeroporto regional, que é onde ele é usado; onde havia dado, o dado
 * manda.
 */
export function estimarMovimento(pop: number, gdp: number, tier: number): number {
  return Math.exp(
    12.6948 + 0.3479 * Math.log(Math.max(0.02, pop)) + 0.3851 * Math.log(gdp) + 0.9290 * tier,
  )
}

